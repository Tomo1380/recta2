 * にまたがり、エリア・業種・条件・働き方のタグを付けてある。コラムTOPの
 * 「探すハブ」(条件/エリア/業種/働き方で探す) はこの tags を whereJsonContains で
 * 絞り込むので、タグ文字列はフロント側のチップ定義 (columns.tsx) と一致させること。
 *
 * body は TipTap の doc JSON、body_html はその SSR スナップショット
 * (フロント /columns/:slug が body_html を直挿入)。実運用では admin が
 * TipTap エディタで書く。slug 基準の updateOrCreate なので再実行しても安全。
 */
class ArticleSeeder extends Seeder
