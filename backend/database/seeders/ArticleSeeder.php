    public function run(): void
    {
        foreach ($this->articles() as $i => $a) {
            $content = [];
            $bodyHtml = '';
            foreach ($a['body'] as [$tag, $text]) {
                if ($tag === 'h2') {
                    $content[] = ['type' => 'heading', 'attrs' => ['level' => 2], 'content' => [['type' => 'text', 'text' => $text]]];
                } else {
                    $content[] = ['type' => 'paragraph', 'content' => [['type' => 'text', 'text' => $text]]];
                }
                $escaped = htmlspecialchars($text, ENT_QUOTES, 'UTF-8');
                $bodyHtml .= $tag === 'h2' ? "<h2>{$escaped}</h2>" : "<p>{$escaped}</p>";
            }

            Article::updateOrCreate(
                ['slug' => $a['slug']],
                [
                    'title' => $a['title'],
                    'excerpt' => $a['excerpt'],
                    'body' => ['type' => 'doc', 'content' => $content],
                    'body_html' => $bodyHtml,
                    'thumbnail_url' => $a['thumbnail'],
                    'category' => $a['category'],
                    'section' => $a['section'],
                    'tags' => $a['tags'],
                    'status' => 'published',
                    'published_at' => now()->subDays($i + 1),
                ],
            );
        }
    }

