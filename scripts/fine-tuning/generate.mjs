// 店舗紹介系として [STORE:ID] マーカー付き回答を出す condition のホワイトリスト
const STORE_RECOMMENDATION_CONDITIONS = new Set([
  'beginner',
  'high_wage',
  'trial',
  'daily_pay',
  'weekly1',
  'norma_low',
  'age30',
  'calm',
  'free_dress',
]);

function expandArea(stores) {
  const out = [];
  // タネ
  for (const seed of areaSeeds) out.push(makeMessage(seed.q, seed.a));
  // パターン A/B: 全エリア × 全条件
  const condKeys = Object.keys(CONDITIONS);
  for (const area of AREAS) {
    for (const condKey of condKeys) {
      const phrase = CONDITIONS[condKey].phrase;
      // 店舗紹介に向く condition だけ実店舗 [STORE:ID] 付きにする
      const useStoreCards = stores && STORE_RECOMMENDATION_CONDITIONS.has(condKey);
      const storeAnswer = useStoreCards
        ? buildAreaConditionAnswerWithStores(area.key, condKey, stores)
        : buildAreaConditionAnswer(area.key, condKey);
      // パターン A: 〜の店ある？  ← 店舗カード入り（条件マッチ時）
      out.push(makeMessage(`${area.key}で${phrase}の店ある？`, storeAnswer));
      // パターン A 別語尾  ← 店舗カード入り（条件マッチ時）
      out.push(makeMessage(`${area.key}で${phrase}の店、教えて`, storeAnswer));
      // パターン B  ← 解説のみ（学習に解説バリエが残るよう確保）
      out.push(makeMessage(`${area.key}って${phrase}の店ありますか？`, buildAreaConditionAnswer(area.key, condKey)));
    }
  }
  // パターン C: エリア × 時給帯（9 × 8 = 72）
  for (const area of AREAS) {
    for (const wage of [4000, 5000, 6000, 7000, 8000, 10000, 12000, 15000]) {
      out.push(makeMessage(`${area.key}で時給${wage.toLocaleString()}円って現実的？`, buildAreaWageAnswer(area.key, wage)));
    }
  }
  // パターン D: エリア × 年齢（9 × 9 = 81）
  for (const area of AREAS) {
    for (const age of [19, 20, 22, 25, 28, 30, 33, 35, 38]) {
      out.push(makeMessage(`${age}歳で${area.key}って厳しい？`, buildAreaAgeAnswer(area.key, age)));
    }
  }
  return out;
}

function expandFeature() {
  const out = [];
  // タネ
  for (const seed of featureSeeds) out.push(makeMessage(seed.q, seed.a));
  // テンプレ × 特徴
  for (const tmpl of featureTemplates) {
    for (const feature of FEATURES) {
      out.push(makeMessage(tmpl.q({ feature }), tmpl.a({ feature })));
    }
  }
  // 不足分の補強: 特徴を絞った別パターン質問
  for (const feature of FEATURES.slice(0, 30)) {
    out.push(makeMessage(`${feature}が条件の店だとおすすめどこ？`, buildFeatureAnswer(feature)));
  }
  for (const feature of FEATURES.slice(30, 60)) {
    out.push(makeMessage(`${feature}を希望してます。候補ありますか？`, buildFeatureAnswer(feature)));
  }
  return out;
}

function dedupAndCap(items, cap) {
  const seen = new Set();
  const out = [];
  for (const item of items) {
    const key = crypto.createHash('sha1').update(item.messages[1].content).digest('hex');
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
    if (out.length >= cap) break;
  }
  return out;
}

